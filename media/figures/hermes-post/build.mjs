// Builds the Hermes post figures to astro/src/assets/blog/yellowhammer-vs-hermes-agent/.
//
//   node media/figures/hermes-post/build.mjs          build every figure, then check the output
//   node media/figures/hermes-post/build.mjs fig-1    build one figure (id prefix)
//   node media/figures/hermes-post/build.mjs --css    rewrite the generated `fig-*` block of
//                                                      astro/src/styles/blog.css from PALETTE
//
// Framework-free: no dependencies beyond Node and the project's iso kit.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as cover from "./cover.mjs";
import * as fig1 from "./fig1.mjs";
import * as fig2 from "./fig2.mjs";
import * as fig3 from "./fig3.mjs";
import { CLASSES, PALETTE } from "./lib.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const OUT = resolve(root, "astro/src/assets/blog/yellowhammer-vs-hermes-agent");
const BLOG_CSS = resolve(root, "astro/src/styles/blog.css");
const MAX_BYTES = 150 * 1024;
const FORBIDDEN = /<style|style=|<script|foreignObject|href="http|var\(/g;

const FIGURES = [fig1, fig2, fig3];

const START =
	"/* fig:start (generated by media/figures/hermes-post/build.mjs --css; do not edit) */";
const END = "/* fig:end */";

function cssBlock() {
	const pair = ([l, d]) => `light-dark(${l}, ${d})`;
	const rules = Object.entries(PALETTE).map(([name, p]) => {
		const decl = [];
		if (p.fill)
			decl.push(`fill: ${p.token ? `var(${p.token})` : pair(p.fill)}`);
		if (p.stroke) {
			decl.push("fill: none");
			decl.push(`stroke: ${p.token ? `var(${p.token})` : pair(p.stroke)}`);
			decl.push(`stroke-width: ${p.width}`);
			// A token stroke already carries its own alpha; reset the fallback attribute's.
			if (p.alpha) decl.push(`stroke-opacity: ${p.token ? 1 : p.alpha}`);
			if (p.dash) decl.push(`stroke-dasharray: ${p.dash}`);
			decl.push("stroke-linejoin: round", "stroke-linecap: round");
		}
		return `.${name} {\n\t${decl.join(";\n\t")};\n}`;
	});
	rules.push(
		".fig-sans {\n\tfont-family: var(--font-sans);\n}",
		".fig-mono {\n\tfont-family: var(--font-mono);\n}",
	);
	return `${START}\n${rules.join("\n")}\n${END}`;
}

function syncCss(write) {
	const css = readFileSync(BLOG_CSS, "utf8");
	const block = cssBlock();
	const a = css.indexOf(START);
	const b = css.indexOf(END);
	if (a === -1 || b === -1) {
		if (!write)
			throw new Error("blog.css has no fig block; run build.mjs --css");
		writeFileSync(BLOG_CSS, `${css.trimEnd()}\n\n${block}\n`);
		return;
	}
	const next = css.slice(0, a) + block + css.slice(b + END.length);
	if (next === css) return;
	if (!write)
		throw new Error("blog.css fig block is out of date; run build.mjs --css");
	writeFileSync(BLOG_CSS, next);
}

const args = process.argv.slice(2);
if (args.includes("--css")) {
	syncCss(true);
	console.log("blog.css fig block written");
	process.exit(0);
}

syncCss(false);
mkdirSync(OUT, { recursive: true });
let failed = false;
for (const f of FIGURES) {
	if (args[0] && !f.id.startsWith(args[0])) continue;
	const svg = f.build();
	const bad = svg.match(FORBIDDEN);
	const used = new Set(
		[...svg.matchAll(/class="([^"]+)"/g)].flatMap((m) => m[1].split(" ")),
	);
	const unknown = [...used].filter((c) => !CLASSES.includes(c));
	const bytes = Buffer.byteLength(svg);
	if (bad || unknown.length || bytes > MAX_BYTES) {
		failed = true;
		console.error(`${f.file}: FAIL`, { forbidden: bad, unknown, bytes });
		continue;
	}
	writeFileSync(resolve(OUT, f.file), svg);
	console.log(
		`${f.file}: ${(bytes / 1024).toFixed(1)} KB, ${used.size} classes`,
	);
}

// The cover: an SVG source kept here, rasterised to a 1200x630 PNG with headless Chrome.
if (!args[0] || "cover".startsWith(args[0])) {
	const CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome";
	const PNG = resolve(
		root,
		"astro/public/blog/yellowhammer-vs-hermes-agent/cover.png",
	);
	writeFileSync(resolve(here, "cover.svg"), cover.build());
	const html = resolve(tmpdir(), "yh-cover.html");
	writeFileSync(
		html,
		`<!doctype html><meta charset="utf-8"><body style="margin:0"><img alt="" src="file://${resolve(here, "cover.svg")}" width="1200" height="630" style="display:block"></body>`,
	);
	if (existsSync(CHROME)) {
		mkdirSync(dirname(PNG), { recursive: true });
		execFileSync(
			CHROME,
			[
				"--headless",
				`--screenshot=${PNG}`,
				"--window-size=1200,630",
				"--hide-scrollbars",
				`file://${html}`,
			],
			{ stdio: "ignore" },
		);
		console.log(
			`cover.png: ${(readFileSync(PNG).length / 1024).toFixed(0)} KB`,
		);
	} else {
		console.warn("Chrome not found; cover.png not rebuilt");
	}
}
process.exit(failed ? 1 : 0);
